package shares

// FTP / FTPS with vsftpd.
//
// Samba enforces per-share, per-user rights itself; vsftpd only knows file
// permissions, and every NAS user can write to every share's folder (the
// shared "nasusers" group). So each user gets their own FTP world:
//
//	/srv/nasftp/alice/Photos  -> bind mount of /data/media/Photos (read-write)
//	/srv/nasftp/alice/Docs    -> bind mount of /data/media/Docs, remounted read-only
//
// vsftpd locks ("chroots") alice into /srv/nasftp/alice: she sees exactly
// the shares she has rights on, with the same rights as over SMB.

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"readynas/internal/store"
)

func renderVsftpd(st store.State, root, certDir string) string {
	tls := "YES"
	if st.Settings.FTPAllowPlain {
		tls = "NO"
	}
	return `# Generated by nasd. Do not edit: changes are overwritten.
listen=YES
listen_ipv6=NO
anonymous_enable=NO

# NAS users log in with their password (PAM service without the
# "valid login shell" check: NAS accounts have no shell).
local_enable=YES
pam_service_name=nasd-ftp
userlist_enable=YES
userlist_deny=NO
userlist_file=/etc/nasd-ftp.users

# Each user is locked into their own view of the shares.
chroot_local_user=YES
user_sub_token=$USER
local_root=` + root + `/$USER
write_enable=YES
local_umask=002
hide_ids=YES

# Passive mode: data connections on a fixed port range.
pasv_enable=YES
pasv_min_port=40000
pasv_max_port=40100

# FTPS: encrypted with the same certificate as the web interface.
ssl_enable=YES
rsa_cert_file=` + filepath.Join(certDir, "tls.crt") + `
rsa_private_key_file=` + filepath.Join(certDir, "tls.key") + `
ssl_ciphers=HIGH
require_ssl_reuse=NO
force_local_logins_ssl=` + tls + `
force_local_data_ssl=` + tls + `
`
}

const pamFTP = `# Generated by nasd: password check for FTP logins.
auth     required pam_unix.so
account  required pam_unix.so
session  required pam_unix.so
`

// sshRule keeps NAS users off SSH: they now have a Linux password (for
// FTP), and even with no shell, SSH would let them open network tunnels.
const sshRule = "# Generated by nasd: NAS accounts are for file sharing only.\nDenyGroups " + Group + "\n"

// ftpViews lists the bind mounts to create: dir -> (source, read-only).
type ftpMount struct {
	Dir, Source string
	ReadOnly    bool
}

func ftpViews(st store.State, root string) (map[string][]ftpMount, []string) {
	views := map[string][]ftpMount{}
	var users []string
	for _, u := range st.Users {
		if u.Admin {
			continue
		}
		users = append(users, u.Name)
		for _, sh := range st.Shares {
			access := sh.Access[u.Name]
			if !sh.FTP || access == "" {
				continue
			}
			views[u.Name] = append(views[u.Name], ftpMount{
				Dir: filepath.Join(root, u.Name, sh.Name), Source: sh.Path, ReadOnly: access == "ro",
			})
		}
	}
	sort.Strings(users)
	return views, users
}

// ReleaseFTPViews unmounts every FTP view (they keep volumes busy, e.g.
// while enabling quotas). Apply recreates them.
func (s *Service) ReleaseFTPViews(ctx context.Context) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.unmountFTPViews(ctx)
}

func (s *Service) unmountFTPViews(ctx context.Context) {
	data, _ := os.ReadFile(s.ProcMounts)
	var mounted []string
	for _, line := range strings.Split(string(data), "\n") {
		if f := strings.Fields(line); len(f) > 1 && strings.HasPrefix(f[1], s.FTPRoot+"/") {
			mounted = append(mounted, f[1])
		}
	}
	slices.Sort(mounted)
	slices.Reverse(mounted) // deepest first
	for _, m := range mounted {
		// -l (lazy): an open FTP session doesn't block the change.
		s.Run(ctx, "umount", "-l", m)
	}
}

func (s *Service) applyFTP(ctx context.Context, st store.State) error {
	s.unmountFTPViews(ctx)
	// Remove the now-empty share directories from earlier views.
	userDirs, _ := os.ReadDir(s.FTPRoot)
	for _, ud := range userDirs {
		subs, _ := os.ReadDir(filepath.Join(s.FTPRoot, ud.Name()))
		for _, sd := range subs {
			os.Remove(filepath.Join(s.FTPRoot, ud.Name(), sd.Name())) // only succeeds if empty
		}
	}
	if !st.Settings.FTPEnabled {
		return s.service(ctx, false, "vsftpd")
	}

	views, users := ftpViews(st, s.FTPRoot)
	for _, u := range users {
		// vsftpd enters the user's home before anything else (and fails with
		// "cannot change directory" if it doesn't exist): the FTP view is
		// the NAS user's home.
		if home, err := s.UserHome(u); err == nil && home != filepath.Join(s.FTPRoot, u) {
			if _, err := s.Run(ctx, "usermod", "--home", filepath.Join(s.FTPRoot, u), u); err != nil {
				return err
			}
		}
		// vsftpd refuses a chroot the user can write to: root-owned, 0555.
		home := filepath.Join(s.FTPRoot, u)
		if err := os.MkdirAll(home, 0o755); err != nil {
			return err
		}
		os.Chmod(home, 0o755) // writable while we create the share folders...
		for _, m := range views[u] {
			if _, err := os.Stat(m.Source); err != nil {
				continue // volume not mounted (yet)
			}
			if err := os.MkdirAll(m.Dir, 0o755); err != nil {
				return err
			}
			if _, err := s.Run(ctx, "mount", "--bind", m.Source, m.Dir); err != nil {
				return err
			}
			if m.ReadOnly {
				// A bind mount is created read-write; read-only needs a remount.
				if _, err := s.Run(ctx, "mount", "-o", "remount,bind,ro", m.Dir); err != nil {
					return err
				}
			}
		}
		os.Chmod(home, 0o555) // ...then locked, as vsftpd requires
	}
	files := map[string]string{
		s.VsftpdConf:  renderVsftpd(st, s.FTPRoot, s.CertDir),
		s.PamFTP:      pamFTP,
		s.FTPUserList: strings.Join(users, "\n") + "\n",
	}
	for path, content := range files {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
	}
	if err := s.service(ctx, true, "vsftpd"); err != nil {
		return err
	}
	_, err := s.Run(ctx, "systemctl", "restart", "vsftpd") // vsftpd has no reload
	return err
}

// applySSHRule installs the SSH rule once (and reloads sshd if it changed).
func (s *Service) applySSHRule(ctx context.Context) {
	if _, err := os.Stat(filepath.Dir(s.SSHDropIn)); err != nil {
		return // no OpenSSH server
	}
	if old, _ := os.ReadFile(s.SSHDropIn); string(old) == sshRule {
		return
	}
	if os.WriteFile(s.SSHDropIn, []byte(sshRule), 0o644) == nil {
		s.Run(ctx, "systemctl", "try-reload-or-restart", "ssh")
	}
}
