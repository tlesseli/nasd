package sysconf

// Automatic security updates. Debian's unattended-upgrades does the work
// (daily, through the apt-daily timers); nasd only switches it on or off,
// sets the optional automatic restart, and reads its log to tell what it
// installed. Kernel updates reach the ReadyNAS boot flash through the
// nas-flash-sync hook of the image.

import (
	"bufio"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"readynas/internal/store"
)

// Files nasd writes in apt.conf.d. 20auto-upgrades is Debian's own switch
// file (the same one "dpkg-reconfigure unattended-upgrades" writes); 52 comes
// after Debian's 50unattended-upgrades, so its values win.
const (
	autoUpgradesFile = "20auto-upgrades"
	nasdUnattended   = "52nasd-unattended-upgrades"
)

func (s *Service) aptConfDir() string {
	if s.AptConfDir != "" {
		return s.AptConfDir
	}
	return "/etc/apt/apt.conf.d"
}

func (s *Service) uuLog() string {
	if s.UnattendedLog != "" {
		return s.UnattendedLog
	}
	return "/var/log/unattended-upgrades/unattended-upgrades.log"
}

func (s *Service) rebootFile() string {
	if s.RebootRequiredFile != "" {
		return s.RebootRequiredFile
	}
	return "/run/reboot-required"
}

// SaveAutoUpdates stores and applies the automatic update settings.
func (s *Service) SaveAutoUpdates(u store.UpdateSettings) error {
	if u.RebootHour < 0 || u.RebootHour > 23 || u.RebootMinute < 0 || u.RebootMinute > 59 {
		return errors.New("invalid restart time")
	}
	if err := s.Store.Update(func(st *store.State) error {
		u.LastReported = st.Updates.LastReported // not the browser's to set
		st.Updates = u
		return nil
	}); err != nil {
		return err
	}
	return s.ApplyAutoUpdates()
}

// ApplyAutoUpdates writes apt's configuration from the state (at start-up
// too: the state is the reference, e.g. after a settings restore).
func (s *Service) ApplyAutoUpdates() error {
	u := s.Store.Read().Updates
	on := map[bool]string{true: "1", false: "0"}
	periodic := "// Generated by nasd (System > Updates). Changes made here are replaced.\n" +
		"APT::Periodic::Update-Package-Lists \"1\";\n" +
		"APT::Periodic::Unattended-Upgrade \"" + on[!u.AutoDisabled] + "\";\n"
	reboot := "// Generated by nasd (System > Updates). Changes made here are replaced.\n" +
		fmt.Sprintf("Unattended-Upgrade::Automatic-Reboot \"%t\";\n", u.AutoReboot) +
		"Unattended-Upgrade::Automatic-Reboot-WithUsers \"true\";\n" +
		fmt.Sprintf("Unattended-Upgrade::Automatic-Reboot-Time \"%02d:%02d\";\n", u.RebootHour, u.RebootMinute)
	for name, content := range map[string]string{autoUpgradesFile: periodic, nasdUnattended: reboot} {
		path := filepath.Join(s.aptConfDir(), name)
		if old, err := os.ReadFile(path); err == nil && string(old) == content {
			continue
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// AutoRun is one run of unattended-upgrades that had something to install.
type AutoRun struct {
	Time     time.Time `json:"time"`
	Packages []string  `json:"packages"`
	OK       bool      `json:"ok"`
	Error    string    `json:"error,omitempty"`
}

// AutoRuns reads unattended-upgrades' log: the time of its last run, and
// the runs that installed (or tried to install) something, oldest first.
func (s *Service) AutoRuns() (last time.Time, runs []AutoRun) {
	f, err := os.Open(s.uuLog())
	if err != nil {
		return
	}
	defer f.Close()
	var cur *AutoRun
	flush := func() {
		if cur != nil && len(cur.Packages) > 0 {
			runs = append(runs, *cur)
		}
		cur = nil
	}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		// "2026-11-10 06:52:40,645 INFO Starting unattended upgrades script"
		line := sc.Text()
		if len(line) < 24 {
			continue
		}
		t, err := time.ParseInLocation("2006-01-02 15:04:05", line[:19], time.Local)
		if err != nil {
			continue
		}
		level, msg, _ := strings.Cut(strings.TrimSpace(line[23:]), " ")
		switch {
		case msg == "Starting unattended upgrades script":
			flush()
			cur, last = &AutoRun{Time: t}, t
		case cur == nil:
		case strings.HasPrefix(msg, "Packages that will be upgraded:"):
			cur.Packages = append(cur.Packages, strings.Fields(strings.TrimPrefix(msg, "Packages that will be upgraded:"))...)
		case msg == "All upgrades installed":
			cur.OK = true
		case level == "ERROR" && cur.Error == "":
			cur.Error = msg
		}
	}
	flush()
	return last, runs
}

// RebootRequired: an installed update waits for a restart, and the
// packages that asked for it.
func (s *Service) RebootRequired() (bool, []string) {
	if _, err := os.Stat(s.rebootFile()); err != nil {
		return false, nil
	}
	data, _ := os.ReadFile(s.rebootFile() + ".pkgs")
	var pkgs []string
	for _, p := range strings.Fields(string(data)) {
		if !containsStr(pkgs, p) {
			pkgs = append(pkgs, p)
		}
	}
	return true, pkgs
}

func containsStr(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

// CheckAutoUpdates reports what unattended-upgrades did since the last
// report: one event per run that installed something, or failed. Called by
// the monitor. The first call only takes note (no flood of old runs).
func (s *Service) CheckAutoUpdates() {
	st := s.Store.Read()
	last, runs := s.AutoRuns()
	if last.IsZero() || !last.After(st.Updates.LastReported) {
		return
	}
	if !st.Updates.LastReported.IsZero() {
		for _, r := range runs {
			if !r.Time.After(st.Updates.LastReported) {
				continue
			}
			list := strings.Join(r.Packages, ", ")
			if r.OK {
				s.Notify("updates_installed", fmt.Sprintf("%d updates installed automatically", len(r.Packages)), "Installed: "+list+".")
			} else {
				s.Notify("updates_failed", "Automatic updates failed", fmt.Sprintf("Installing %s failed: %s. Try Install updates in System > Updates; the log is /var/log/unattended-upgrades/.", list, orText(r.Error, "see the log")))
			}
		}
	}
	s.Store.Update(func(st *store.State) error { st.Updates.LastReported = last; return nil })
}

func orText(s, def string) string {
	if s == "" {
		return def
	}
	return s
}
