package sysconf

// Network configuration with systemd-networkd, and a safety net: a change
// must be confirmed within ConfirmWindow, from the browser, at the new
// address. If not (you can't reach the NAS anymore), the previous
// configuration comes back by itself. This is how routers and managed
// switches avoid locking you out.

import (
	"context"
	"errors"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	"time"

	"readynas/internal/store"
)

const filePrefix = "05-nasd-" // sorts before netplan's/Debian's files: ours win

var BondModes = []string{"active-backup", "balance-alb", "802.3ad"}

type NetworkInfo struct {
	Settings store.NetworkSettings `json:"settings"`
	Pending  *store.NetworkChange  `json:"pending"`
	Physical []string              `json:"physical"` // physical interfaces
	Current  []CurrentAddr         `json:"current"`
	Gateway  string                `json:"gateway"`
}

type CurrentAddr struct {
	Interface string `json:"interface"`
	Address   string `json:"address"` // 192.168.1.50/24
	MTU       int    `json:"mtu"`
	Up        bool   `json:"up"`
}

func (s *Service) Network(ctx context.Context) NetworkInfo {
	st := s.Store.Read()
	info := NetworkInfo{Settings: st.Network, Pending: st.NetworkPending, Physical: s.physical(), Current: []CurrentAddr{}}
	if info.Settings.Interfaces == nil {
		info.Settings.Interfaces = []string{}
	}
	if info.Settings.DNS == nil {
		info.Settings.DNS = []string{}
	}
	ifaces, _ := net.Interfaces()
	for _, ifc := range ifaces {
		if ifc.Flags&net.FlagLoopback != 0 {
			continue
		}
		addrs, _ := ifc.Addrs()
		for _, a := range addrs {
			if ipn, ok := a.(*net.IPNet); ok && ipn.IP.To4() != nil {
				info.Current = append(info.Current, CurrentAddr{Interface: ifc.Name, Address: a.String(), MTU: ifc.MTU, Up: ifc.Flags&net.FlagUp != 0})
			}
		}
	}
	if out, err := s.Run(ctx, "ip", "-4", "route", "show", "default"); err == nil {
		if f := strings.Fields(string(out)); len(f) >= 3 {
			info.Gateway = f[2]
		}
	}
	return info
}

func (s *Service) physical() []string {
	dirs, _ := filepath.Glob(filepath.Join(s.Sys, "class", "net", "*", "device"))
	out := []string{}
	for _, d := range dirs {
		out = append(out, filepath.Base(filepath.Dir(d)))
	}
	sort.Strings(out)
	return out
}

func (s *Service) validateNetwork(n *store.NetworkSettings) error {
	if !n.Managed {
		*n = store.NetworkSettings{}
		return nil
	}
	phys := s.physical()
	if len(n.Interfaces) == 0 {
		return errors.New("choose a network interface")
	}
	for _, i := range n.Interfaces {
		if !slices.Contains(phys, i) {
			return fmt.Errorf("unknown interface %q", i)
		}
	}
	if len(n.Interfaces) > 1 && n.Bond == "" {
		return errors.New("several interfaces must be bonded")
	}
	if n.Bond != "" && !slices.Contains(BondModes, n.Bond) {
		return errors.New("unknown bonding mode")
	}
	if n.MTU != 0 && (n.MTU < 576 || n.MTU > 9000) {
		return errors.New("MTU must be between 576 and 9000 (9000 = jumbo frames)")
	}
	if n.DHCP {
		n.Address, n.Gateway, n.DNS = "", "", nil
		return nil
	}
	ip, subnet, err := net.ParseCIDR(n.Address)
	if err != nil || ip.To4() == nil {
		return errors.New("address must look like 192.168.1.50/24")
	}
	if n.Gateway != "" {
		gw := net.ParseIP(n.Gateway)
		if gw == nil || !subnet.Contains(gw) {
			return errors.New("the gateway must be an address in the same network (e.g. 192.168.1.1)")
		}
	}
	var dns []string
	for _, d := range n.DNS {
		if d = strings.TrimSpace(d); d == "" {
			continue
		}
		if net.ParseIP(d) == nil {
			return fmt.Errorf("DNS server %q is not an IP address", d)
		}
		dns = append(dns, d)
	}
	if len(dns) > 3 {
		return errors.New("at most 3 DNS servers")
	}
	n.DNS = dns
	return nil
}

// renderNetwork returns the systemd-networkd files (name -> content).
func renderNetwork(n store.NetworkSettings) map[string]string {
	files := map[string]string{}
	if !n.Managed {
		return files
	}
	link := ""
	if n.MTU > 0 {
		link = fmt.Sprintf("\n[Link]\nMTUBytes=%d\n", n.MTU)
	}
	addressing := "[Network]\n"
	if n.DHCP {
		addressing += "DHCP=ipv4\n"
	} else {
		addressing += "Address=" + n.Address + "\n"
		if n.Gateway != "" {
			addressing += "Gateway=" + n.Gateway + "\n"
		}
		for _, d := range n.DNS {
			addressing += "DNS=" + d + "\n"
		}
	}
	header := "# Generated by nasd. Do not edit: changes are overwritten.\n"
	if n.Bond == "" {
		files[filePrefix+n.Interfaces[0]+".network"] = header + "[Match]\nName=" + n.Interfaces[0] + "\n" + link + "\n" + addressing
		return files
	}
	// Bonding: several ports act as one link, for failover (active-backup)
	// or more total bandwidth (balance-alb; 802.3ad needs a switch with LACP).
	bond := "[NetDev]\nName=bond0\nKind=bond\n\n[Bond]\nMode=" + n.Bond + "\nMIIMonitorSec=100ms\n"
	if n.Bond == "802.3ad" {
		bond += "LACPTransmitRate=fast\nTransmitHashPolicy=layer3+4\n"
	}
	files[filePrefix+"bond0.netdev"] = header + bond
	for _, i := range n.Interfaces {
		files[filePrefix+i+".network"] = header + "[Match]\nName=" + i + "\n" + link + "\n[Network]\nBond=bond0\n"
	}
	files[filePrefix+"bond0.network"] = header + "[Match]\nName=bond0\n" + link + "\n" + addressing
	return files
}

// SetNetwork applies a configuration and starts the confirmation countdown.
func (s *Service) SetNetwork(ctx context.Context, n store.NetworkSettings) (time.Time, error) {
	if err := s.validateNetwork(&n); err != nil {
		return time.Time{}, err
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	st := s.Store.Read()
	if st.NetworkPending != nil {
		return time.Time{}, errors.New("a network change is waiting for confirmation")
	}
	previous := st.Network
	if err := s.writeNetwork(ctx, previous, n); err != nil {
		s.writeNetwork(ctx, n, previous) // put things back as they were
		return time.Time{}, err
	}
	deadline := s.Now().Add(s.ConfirmWindow)
	err := s.Store.Update(func(st *store.State) error {
		st.Network = n
		st.NetworkPending = &store.NetworkChange{Previous: previous, Deadline: deadline}
		return nil
	})
	s.armRollback(s.ConfirmWindow)
	return deadline, err
}

// ConfirmNetwork keeps the new configuration.
func (s *Service) ConfirmNetwork() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.rollback != nil {
		s.rollback.Stop()
	}
	return s.Store.Update(func(st *store.State) error {
		if st.NetworkPending == nil {
			return errors.New("nothing to confirm")
		}
		st.NetworkPending = nil
		return nil
	})
}

// ResumePending is called at startup: a change applied before a restart
// and never confirmed still gets rolled back.
func (s *Service) ResumePending() {
	st := s.Store.Read()
	if st.NetworkPending == nil {
		return
	}
	left := st.NetworkPending.Deadline.Sub(s.Now())
	s.mu.Lock()
	s.armRollback(max(left, time.Second))
	s.mu.Unlock()
}

func (s *Service) armRollback(after time.Duration) {
	if s.rollback != nil {
		s.rollback.Stop()
	}
	s.rollback = time.AfterFunc(after, func() { s.Rollback(context.Background()) })
}

// Rollback restores the previous configuration if the change is still pending.
func (s *Service) Rollback(ctx context.Context) {
	s.mu.Lock()
	defer s.mu.Unlock()
	st := s.Store.Read()
	if st.NetworkPending == nil {
		return
	}
	prev := st.NetworkPending.Previous
	if err := s.writeNetwork(ctx, st.Network, prev); err != nil {
		s.Notify("resolved", "Network rollback failed", err.Error())
	}
	s.Store.Update(func(st *store.State) error {
		st.Network = prev
		st.NetworkPending = nil
		return nil
	})
	s.Notify("resolved", "Network change rolled back",
		"The new network settings were not confirmed in time, so the previous ones were restored.")
}

// writeNetwork replaces our files and restarts systemd-networkd.
func (s *Service) writeNetwork(ctx context.Context, from, to store.NetworkSettings) error {
	old, _ := filepath.Glob(filepath.Join(s.NetworkDir, filePrefix+"*"))
	for _, f := range old {
		os.Remove(f)
	}
	for name, content := range renderNetwork(to) {
		if err := os.WriteFile(filepath.Join(s.NetworkDir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	// A bond that is no longer configured stays in the kernel until removed.
	if from.Bond != "" && to.Bond == "" {
		s.Run(ctx, "ip", "link", "delete", "bond0")
	}
	if _, err := s.Run(ctx, "systemctl", "restart", "systemd-networkd"); err != nil {
		return err
	}
	// networkd doesn't undo a setting that disappears from the config: put a
	// custom MTU back to the standard 1500 explicitly.
	if from.MTU > 0 && to.MTU == 0 {
		for _, i := range from.Interfaces {
			s.Run(ctx, "ip", "link", "set", "dev", i, "mtu", "1500")
		}
		if from.Bond != "" && to.Bond != "" {
			s.Run(ctx, "ip", "link", "set", "dev", "bond0", "mtu", "1500")
		}
	}
	// Re-apply to every interface we touched (releases or takes addresses).
	ifaces := slices.Concat(from.Interfaces, to.Interfaces)
	slices.Sort(ifaces)
	for _, i := range slices.Compact(ifaces) {
		s.Run(ctx, "networkctl", "reconfigure", i)
	}
	return nil
}
